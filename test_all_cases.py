def run_tests():
    total = len(TEST_CASES)
    passed = 0
    failed = 0
    failed_names = []

    for idx, tc in enumerate(TEST_CASES):
        name = tc["name"]
        raw = tc["raw"]
        expected = tc["expectedV3"]

        config = parse_raw(raw)
        result = eu(config)

        count_match = len(result) == len(expected)
        all_match = count_match and all(r == e for r, e in zip(result, expected))

        if all_match:
            passed += 1
            print(f"  [{idx+1:2d}/{total}] PASS  {name} ({len(result)} entries)")
        else:
            failed += 1
            failed_names.append(name)
            print(f"  [{idx+1:2d}/{total}] FAIL  {name}")
            print(f"         Length: got={len(result)} expected={len(expected)}")
            max_len = max(len(result), len(expected))
            mismatches = 0
            for i in range(max_len):
                gen = result[i] if i < len(result) else "---"
                exp = expected[i] if i < len(expected) else "---"
                if gen != exp:
                    mismatches += 1
                    if mismatches <= 10:
                        print(f"         [{i:3d}] got={gen} exp={exp}")
            if mismatches > 10:
                print(f"         ... and {mismatches - 10} more mismatches")
            print(f"         Total mismatches: {mismatches}")

    print()
    print("=" * 60)
    print(f"RESULTS: {passed}/{total} passed, {failed}/{total} failed")
    if failed_names:
        print(f"FAILED: {', '.join(failed_names)}")
    print("=" * 60)

    return failed == 0


